#include <setjmp.h>   /* setjmp(), longjmp() を使うためのヘッダ */
#include <stdio.h>    /* fprintf(), printf() を使うためのヘッダ */
#include <stdlib.h>   /* exit() を使うためのヘッダ */
#include "mysub.h"    /* getint() の宣言が入っている想定の独自ヘッダ */

/*
    jmp_buf は、「あとでこの場所に戻るための実行状態」を保存するための型です。

    setjmp(env) を呼ぶと、
    - 現在の関数呼び出しの流れ
    - スタックの復帰に必要な情報
    - 実装依存のレジスタ状態
    などが env に保存されます。

    その後、別の深い関数の中で longjmp(env, 値) を呼ぶと、
    通常の return による段階的な巻き戻しをせずに、
    直接 setjmp() を呼んだ地点へジャンプできます。

    これは C における簡易的な「例外処理風」の仕組みとしてよく説明されますが、
    実際には C 言語処理系と実行時環境が提供する非局所ジャンプ
    (non-local jump) の機能です。
*/
static jmp_buf env;

/*
    指定された item 番号の内容を表示する関数です。

    引数:
        num : 表示したい項目番号

    この関数では、
    - num <= 10 なら正常な項目として表示
    - num > 10 ならエラーとみなし、longjmp() で main() 側へ復帰
    という動作を行っています。

    重要:
    longjmp() は普通の return と異なり、この関数の呼び出し元へ順番に戻るのではなく、
    以前 setjmp() した地点へ一気に飛びます。
    そのため、途中の関数 do_show() などは「return されずに」飛び越されます。
*/
void do_show_item(int num)
{
    /*
        存在しない item 番号を検出した場合のエラー処理です。
        stderr にエラーメッセージを出力します。

        stderr は標準エラー出力であり、
        通常の結果表示(stdout)とは分けて扱われます。
        エラーメッセージを stderr に出すのは UNIX 的に自然な設計です。
    */
    if (num > 10) {
        fprintf(stderr, "no such item: %d\n", num);

        /*
            longjmp(env, 1) により、直前ではなく
            「対応する setjmp(env) を実行した地点」へジャンプします。

            ここで 1 を渡しているので、setjmp(env) の返り値は
            初回呼び出し時の 0 ではなく 1 になります。

            つまり main() 側では
                if (setjmp(env) != 0)
            が真となり、「エラーから回復した」処理に入れます。

            これにより、
            do_show_item() → do_show() → main() の通常の return ではなく、
            エラー時だけまとめて main() に戻る流れを作っています。
        */
        longjmp(env, 1);
    }

    /*
        正常な item 番号であれば、その項目の表示を行います。
        ここではサンプルなので詳細内容ではなく簡易メッセージだけ出しています。
    */
    printf("item %d is ...\n", num);
}

/*
    項目番号を入力させて、その項目を表示する関数です。

    処理の流れ:
    1. getint() で整数入力を受け取る
    2. その値を do_show_item() に渡す

    もし do_show_item() の中で longjmp() が起きた場合、
    この関数には制御は戻ってきません。
    つまり、この関数の残り処理や return は飛ばされて、
    直接 main() 内の setjmp() 地点へ戻ります。
*/
void do_show(void)
{
    /*
        getint() はおそらく
        - 指定したメッセージを表示し
        - 整数を読み取って返す
        補助関数です。

        ユーザ入力を受け取って item 番号を決めています。
    */
    int item_no = getint("item number? ");

    /*
        入力された番号に対応する項目を表示します。
        不正な番号なら do_show_item() の中で longjmp() されます。
    */
    do_show_item(item_no);
}

/*
    入力処理を行うダミー関数です。
    実際には単にメッセージを出すだけですが、
    コマンド 1 に対応する処理の例として置かれています。
*/
void do_input(void)
{
    printf("input done\n");
}

/*
    プログラム終了用の関数です。

    exit(0) はプロセス全体を正常終了させます。
    単なる return と違い、main() に戻るのではなく
    この時点でプロセスの終了処理へ進みます。

    UNIX/Linux 的には、プロセスは終了時に終了ステータスを親プロセスへ返します。
    ここでの 0 は「正常終了」を意味する慣例的な値です。
*/
void do_end(void)
{
    exit(0);
}

int main(void)
{
    int command;

    /*
        setjmp(env) により、現在地点の実行状態を env に保存します。

        setjmp() の返り値は 2 通りあります。

        1. 最初にこの行を普通に実行したとき
           -> 0 を返す

        2. あとで longjmp(env, 1) などでここへ戻ってきたとき
           -> longjmp() で指定した値（ここでは 1）を返す

        そのため、この if 文は
        - 初回: 偽
        - エラーからの復帰後: 真
        という形で使えます。

        この構造は、例外処理でいう
        「try の開始地点」と「catch 後の回復処理」を
        C で手作業で組んでいるようなものです。
    */
    if (setjmp(env) != 0) {
        /*
            longjmp() によってここへ戻ってきた場合に実行されます。
            つまり、「エラーが起きたが、プログラム全体は終了せず、
            メインループに戻って再開できた」ことを示しています。

            このプログラムは、1つのコマンド処理に失敗しても
            即終了せず、次のコマンド入力に戻る設計になっています。
        */
        fprintf(stderr, "error recovered\n");
    }

    /*
        無限ループでコマンドを受け付け続けます。
        これは簡易的な対話型コマンドインタプリタのような構造です。

        longjmp() によって setjmp() 地点へ戻った後も、
        この while ループの位置から再び処理が継続されます。
        正確には setjmp() を含む if 文の次へ進み、再びループに入ります。
    */
    while (1) {
        /*
            ユーザにコマンド番号を入力させます。
            0 = show
            1 = input
            2 = end
        */
        command = getint("command (0=show, 1=input, 2=end)? ");

        /*
            入力されたコマンドに応じて処理を分岐します。
        */
        switch (command) {
        case 0:
            /*
                項目表示処理です。
                ここで呼ばれる do_show() のさらに中で do_show_item() が呼ばれ、
                不正番号なら longjmp() が発生する可能性があります。
            */
            do_show();
            break;

        case 1:
            /*
                入力処理です。
                このサンプルでは単に "input done" を表示します。
            */
            do_input();
            break;

        case 2:
            /*
                終了処理です。
                exit(0) によりプロセス全体が終了します。
            */
            do_end();
            break;

        default:
            /*
                定義されていないコマンド番号が入力された場合の処理です。
                プログラムは終了せず、エラーメッセージを出して
                次の入力待ちへ進みます。
            */
            fprintf(stderr, "unknown command\n");
            break;
        }
    }
}

/*
    ------------------------------------------------------------
    このプログラム全体のアルゴリズム
    ------------------------------------------------------------

    1. main() で setjmp(env) を実行し、
       「エラー時に戻る地点」を保存する

    2. 無限ループで command を受け取る

    3. command に応じて処理を分岐する
       - 0: 項目表示
       - 1: 入力処理
       - 2: 終了
       - その他: エラー表示

    4. 項目表示処理の中で item 番号を入力させる

    5. item 番号が 10 以下なら正常表示
       item 番号が 11 以上なら longjmp(env, 1) で
       main() の setjmp() 地点へ一気に戻る

    6. main() 側では setjmp(env) の返り値が 0 以外になるため、
       "error recovered" を表示してループ継続

    ------------------------------------------------------------
    制御フローのイメージ
    ------------------------------------------------------------

        main
         |
         +-- setjmp(env)  ← 復帰地点を保存
         |
         +-- while (1)
               |
               +-- command 入力
                     |
                     +-- 0 --> do_show()
                     |          |
                     |          +-- item_no 入力
                     |          |
                     |          +-- do_show_item(item_no)
                     |                 |
                     |                 +-- num <= 10 --> 表示して return
                     |                 |
                     |                 +-- num > 10  --> longjmp(env, 1)
                     |                                      |
                     |                                      +--> setjmp の地点へ戻る
                     |
                     +-- 1 --> do_input()
                     |
                     +-- 2 --> do_end() --> exit(0)
                     |
                     +-- その他 --> unknown command

    ------------------------------------------------------------
    UNIX/Linux のシステムコールとの関係
    ------------------------------------------------------------

    このコードで直接使っているのは setjmp/longjmp, printf/fprintf, exit であり、
    いずれも「Cライブラリ関数」です。
    厳密には setjmp/longjmp はシステムコールではありません。

    ただし、UNIX/Linux プログラミングの文脈では非常に重要です。
    なぜなら、
    - exit() は最終的にプロセス終了に関わる OS の仕組みと結びつく
    - fprintf()/printf() は内部で write() 系の出力処理に至る
    - エラー時に深い呼び出しから脱出する制御手法として使われる
    からです。

    つまりこのコードは、
    「OS に近い C プログラムで、失敗時の制御フローをどう設計するか」
    を学ぶサンプルとして読むとよいです。

    ------------------------------------------------------------
    注意点
    ------------------------------------------------------------

    1. longjmp() は強力ですが危険でもあります。
       通常の return を飛ばすため、
       途中で解放すべき資源（メモリ、ファイル、ロックなど）があると
       後始末が漏れる可能性があります。

    2. setjmp() と longjmp() の間で変更された自動変数の扱いには注意が必要です。
       特に longjmp() 後に値が保証されないケースがあり、
       必要なら volatile を使うことがあります。

    3. 現代的な大規模プログラムでは、
       単純なエラーコード返却や構造化された設計で代替されることも多いですが、
       UNIX 的な低レベル C の世界では今でも知っておく価値があります。
*/
